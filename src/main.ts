document.addEventListener('keydown', (e) => {
  const key = e.key;
  if (key in toolByKey) {
    selectTool(toolByKey[key]);
    e.preventDefault();
    return;
  }
  if (key === '-' || key === '_') {
    cycleBrush(-1);
    e.preventDefault();
  }
  if (key === '=' || key === '+') {
    cycleBrush(1);
    e.preventDefault();
  }
  if (key.toLowerCase() === 'c' && !e.ctrlKey && !e.metaKey) {
    worker.postMessage({ type: 'clear' } satisfies WorkerInput);
    clearCanvas();
    latestFrame = null;
    canvasState = 'fresh';
    e.preventDefault();
  }
  if (key.toLowerCase() === 'g') {
    toggleRecording();
    e.preventDefault();
  }
  // Ctrl+S = save, Ctrl+O = load
  if ((e.ctrlKey || e.metaKey) && key.toLowerCase() === 's') {
    e.preventDefault();
    saveToFile();
  }
  if ((e.ctrlKey || e.metaKey) && key.toLowerCase() === 'o') {
    e.preventDefault();
    (document.getElementById('load-input') as HTMLInputElement).click();
  }
});

// ─── Coordinate helpers ─────────────────────────────────────────
function canvasToGrid(cx: number, cy: number): [number, number] {
  const rect = canvas.getBoundingClientRect();
  const scaleX = canvas.width / rect.width;
  const scaleY = canvas.height / rect.height;
  const gx = Math.floor((cx - rect.left) * scaleX / CELL_PX);
  const gy = Math.floor((cy - rect.top) * scaleY / CELL_PX);
  return [gx, gy];
}

function sendInput(x: number, y: number, active: boolean) {
  if (active) markUserModified();
  worker.postMessage({
    type: 'input',
    x, y, tool, brushSize, active,
  } satisfies WorkerInput);
}

// ─── Mouse / touch handlers ─────────────────────────────────────
function onPointerDown(cx: number, cy: number) {
  mouseDown = true;
  const [gx, gy] = canvasToGrid(cx, cy);
  lastX = gx; lastY = gy;
  if (tool === Tool.EXPLOSIVE) {
    mouseDown = false; // single click, no drag
    const radius = brushSize * 3 + 4;
    worker.postMessage({ type: 'explode', x: gx, y: gy, radius } satisfies WorkerInput);
    return;
  }
  sendInput(gx, gy, true);
}

function onPointerMove(cx: number, cy: number) {
  const [gx, gy] = canvasToGrid(cx, cy);
  if (gx !== lastX || gy !== lastY || mouseDown) {
    lastX = gx; lastY = gy;
    if (mouseDown) sendInput(gx, gy, true);
  }
  updateModeIndicator(cx, cy);
}

function onPointerUp() {
  if (!mouseDown) return;
  mouseDown = false;
  // Post input with active=false on next microtask to let in-progress ticks finish
  setTimeout(() => sendInput(-1, -1, false), 0);
}

