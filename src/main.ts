function randomSceneIndexExcluding(previous: number | null): number {
  if (SCENES.length <= 1) return 0;
  let idx: number;
  do {
    idx = Math.floor(Math.random() * SCENES.length);
  } while (idx === previous);
  return idx;
}

/** Clear the canvas visually (immediately, synchronous). */
function clearCanvas() {
  // Fill the displayed canvas with background gradient
  for (let y = 0; y < GRID_H; y++) {
    const t = y / (GRID_H - 1);
    const bgR = 20 - t * 8;
    const bgG = 15 + t * 10;
    const bgB = 25 + t * 8;
    for (let x = 0; x < GRID_W; x++) {
      const pi = (y * GRID_W + x) * 4;
      gridImgData.data[pi] = bgR;
      gridImgData.data[pi + 1] = bgG;
      gridImgData.data[pi + 2] = bgB;
      gridImgData.data[pi + 3] = 255;
    }
  }
  offCtx.putImageData(gridImgData, 0, 0);
  ctx.imageSmoothingEnabled = false;
  ctx.drawImage(offscreen, 0, 0, CANVAS_W, CANVAS_H);
}

function generateScene(sceneIndex?: number) {
  if (sceneGenerating) return; // debounce: ignore rapid clicks
  sceneGenerating = true;

  const seed = Date.now() ^ (Math.random() * 0x7fffffff | 0);
  if (sceneIndex === undefined) {
    sceneIndex = randomSceneIndexExcluding(lastSceneIndex);
  }
  lastSceneIndex = sceneIndex;
  currentSceneIndex = sceneIndex;

  // Scene transition flash
  const canvasWrap = document.querySelector('.canvas-wrap')!;
  canvasWrap.classList.add('scene-transition');
  setTimeout(() => canvasWrap.classList.remove('scene-transition'), 350);

  // ⭐ Immediately clear the canvas so user sees instant feedback,
  // before the worker even starts its CPU-heavy scene generation.
  worker.postMessage({ type: 'clear' } satisfies WorkerInput);
  clearCanvas();
  latestFrame = null;

  // Generate the scene in the worker (off the main thread)
  const genToken = ++sceneGenCounter;
  pendingGenToken = genToken;
  worker.postMessage({ type: 'generateScene', sceneIndex, seed, genToken } satisfies WorkerInput);

  canvasState = 'autoGenerated';
  showSceneToast(sceneIndex);

  // Randomize wind for each new scene (more fun)
  const randomWind = windStates[Math.floor(Math.random() * windStates.length)];
  windState = randomWind;
  worker.postMessage({ type: 'wind', direction: windState } satisfies WorkerInput);
  const windIdx = windStates.indexOf(windState);
  btnWind.textContent = windLabels[windIdx];
  updateStatusModes();
}

