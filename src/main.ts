// ─── rAF-throttled render loop ──────────────────────────────────
// Decouples rendering from worker tick rate. The worker runs
// independently and only one tick is ever pending. At vsync (60fps),
// we grab the latest frame and render it. This prevents flooding
// the main thread when the worker processes ticks faster than
// the display can refresh.
let latestFrame: Uint8ClampedArray | null = null;
let tickPending = false;
let renderLoopRunning = false;
let sceneGenerating = false; // debounce: ignore generate clicks while worker is busy
let sceneGenCounter = 0;      // incremented on each generateScene call
let pendingGenToken = 0;      // expected genToken to reset sceneGenerating

function queueTick() {
  if (tickPending) return;
  tickPending = true;
  worker.postMessage({ type: 'tick' } satisfies WorkerInput);
}

function renderTick() {
  if (!latestFrame) return;
  const src = latestFrame;
  latestFrame = null;

  gridImgData.data.set(src);
  offCtx.putImageData(gridImgData, 0, 0);
  ctx.imageSmoothingEnabled = false;
  ctx.drawImage(offscreen, 0, 0, CANVAS_W, CANVAS_H);

  // Request next tick only after rendering (backpressure)
  if (!paused) queueTick();
}

function renderLoop(_time: number) {
  if (!paused) renderTick();
  requestAnimationFrame(renderLoop);
}

worker.onmessage = (e: MessageEvent<FrameMessage | StateSnapshotMessage>) => {
  const msg = e.data;
  if (msg.type === 'stateSnapshot') {
    if (pendingSaveResolve) {
      pendingSaveResolve(msg.data);
      pendingSaveResolve = null;
    }
    return;
  }
  if (msg.type !== 'frame') return;

  const src = msg.pixels;
  tickPending = false;

  // GIF recording: capture raw RGBA frame at grid resolution
  if (recording) {
    recordedFrames.push(new Uint8Array(src));
    recordingFrameCount++;
    btnRecord.textContent = `⏺ ${Math.round(recordingFrameCount / RECORD_TOTAL_FRAMES * 100)}%`;

    if (recordingFrameCount >= RECORD_TOTAL_FRAMES) {
      recording = false;
      const capturedFrames = recordedFrames;
      recordedFrames = [];
      encodeGIF(capturedFrames);
      return; // don't render this frame, let encoding happen
    }
  }

  // Store the latest frame for the rAF render loop
  // If we already have a pending frame, it gets replaced so we only
  // render the most recent one (drops intermediate frames at high tick rates).
  latestFrame = src;
  // Only reset the scene generation debounce when the frame WITH the
  // matching genToken arrives.  Stale tick frames from before the
  // generateScene call do NOT reset sceneGenerating.
  if (msg.sceneGenToken === pendingGenToken) {
    sceneGenerating = false;
  }

  // Start rAF loop on first frame
  if (!renderLoopRunning) {
    renderLoopRunning = true;
    requestAnimationFrame(renderLoop);
  }
};

// ─── Save / Load ────────────────────────────────────────────────
const PBOX_MAGIC = 0x50424F58; // 'PBOX' as uint32 LE
let pendingSaveResolve: ((data: ArrayBuffer) => void) | null = null;

function saveToFile() {
  // Request state from worker
  worker.postMessage({ type: 'saveState' } satisfies WorkerInput);
  pendingSaveResolve = (data: ArrayBuffer) => {
    const gridArr = new Uint8Array(data);
    const fileBuf = new ArrayBuffer(8 + data.byteLength);
    const fw = new DataView(fileBuf);
    fw.setUint32(0, PBOX_MAGIC, true);       // magic
    fw.setUint16(4, GRID_W, true);             // width
    fw.setUint16(6, GRID_H, true);             // height
    new Uint8Array(fileBuf, 8).set(gridArr);    // grid + life

    const blob = new Blob([fileBuf], { type: 'application/octet-stream' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `powderbox-${Date.now()}.pbox`;
    a.click();
    URL.revokeObjectURL(url);
  };
}

function loadFromFile(file: File) {
  const reader = new FileReader();
  reader.onload = () => {
    const buf = reader.result as ArrayBuffer;
    const view = new DataView(buf);
    const magic = view.getUint32(0, true);
    if (magic !== PBOX_MAGIC) {
      alert('Not a valid PowderBox save (.pbox) file.');
      return;
    }
    const w = view.getUint16(4, true);
    const h = view.getUint16(6, true);
    if (w !== GRID_W || h !== GRID_H) {
      alert(`Save file has wrong dimensions (${w}×${h}), expected ${GRID_W}×${GRID_H}.`);
      return;
    }
    const payload = buf.slice(8);
    worker.postMessage({ type: 'loadState', data: payload }, [payload]);
    canvasState = 'userModified';
  };
  reader.readAsArrayBuffer(file);
}

// ─── Auto-save to localStorage ─────────────────────────────────
function autoSave() {
  worker.postMessage({ type: 'saveState' } satisfies WorkerInput);
  pendingSaveResolve = (data: ArrayBuffer) => {
    try {
      const bytes = new Uint8Array(data);
      const b64 = btoa(String.fromCharCode(...bytes));
      localStorage.setItem('powderbox_autosave', b64);
    } catch { /* quota exceeded, ignore */ }
  };
}

// Auto-save every 10 seconds while not paused
setInterval(() => {
  if (!paused) autoSave();
}, 10000);

// Restore autosave on load (after worker init)
function tryRestoreAutosave() {
  const b64 = localStorage.getItem('powderbox_autosave');
  if (!b64) return;
  try {
    const bytes = Uint8Array.from(atob(b64), c => c.charCodeAt(0));
    if (bytes.length !== GRID_W * GRID_H * 2) return;
    // Prepend dimensions so the worker's loadState handler can verify
    const meta = new ArrayBuffer(4);
    const mv = new DataView(meta);
    mv.setUint16(0, GRID_W, true);
    mv.setUint16(2, GRID_H, true);
    const combined = new Uint8Array(4 + bytes.length);
    combined.set(new Uint8Array(meta), 0);
    combined.set(bytes, 4);
    const payload = combined.buffer;
    worker.postMessage({ type: 'loadState', data: payload }, [payload]);
    canvasState = 'userModified';
  } catch { /* corrupt autosave, ignore */ }
}

